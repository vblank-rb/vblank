module VBlank
  module Console
    # The hardware each target has, and which of it VBlank drives: one list for each console, one
    # for the desktop program and one for the web page. Each feature is named in plain words, as
    # a reader of the target's documentation would know it (GBATEK, Pan Docs, fullsnes, plutiedev,
    # psx-spx; for the two computer builds, what a player expects of a game's window or page).
    #
    # A feature VBlank drives can name the verbs a game uses for it. On a console those verbs are
    # held to the console's answers table (Console::Answers): a test fails if one is not a verb, or
    # if the console refuses it, so the list cannot say a feature is driven while the build refuses
    # the verb that drives it.
    #
    # Rare add-ons are left out of every list (a printer, a mouse, a light gun, a tilt sensor), and
    # so are corners of the hardware few games used, such as starting a second console over the link
    # cable or the deepest sleep. The README's chart counts these lists,
    # and `ruby tools/where_a_game_runs.rb` draws it.
    #
    #--
    # A new feature goes in its target's list; a gap that lands changes `not_yet` to `driven` and
    # names its verbs where it has any. Then run the tool, and commit the two pictures with it.
    #++
    module HardwareFeatures
      # One thing a target's hardware can do. +driven+ is whether VBlank drives it; +verbs+ are the
      # verbs a game drives it with, where there are any to name.
      Feature = Data.define(:name, :driven, :verbs) do
        def driven? = driven
      end

      # A console, or a computer build, and its features. +console+ is the console's name (:gba),
      # or nil for a computer build, which has no answers table of its own.
      Target = Data.define(:title, :console, :features) do
        def driven_count = features.count(&:driven?)
        def feature_count = features.size
      end

      # A feature VBlank drives, and the verbs a game drives it with.
      def self.driven(name, *verbs) = Feature.new(name, true, verbs)

      # A feature VBlank does not drive yet.
      def self.not_yet(name) = Feature.new(name, false, [])

